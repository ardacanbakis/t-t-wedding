#!/usr/bin/env node
// The story site is plain static HTML (not part of the Next bundle), so it
// can't read process.env. This writes the public Supabase coordinates into
// public/story/config.js at build time; next build then copies it to out/.
// The file is gitignored — it is regenerated on every build.
//
// It also carries supabase/seed.json as window.__TT_SEED: the story renders
// those chapters straight away (and keeps them if Supabase is unreachable or
// paused), then swaps in the live rows once they arrive.

import fs from "node:fs";
import path from "node:path";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || "";
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || "";

const seed = JSON.parse(fs.readFileSync(path.join(process.cwd(), "supabase", "seed.json"), "utf8"));

const target = path.join(process.cwd(), "public", "story", "config.js");
const body =
  "// Generated by tools/write-story-config.mjs — do not edit.\n" +
  "window.__TT_CONFIG = " +
  JSON.stringify({ url, key, basePath }) +
  ";\n" +
  "window.__TT_SEED = " +
  JSON.stringify({ settings: seed.settings, chapters: seed.chapters }) +
  ";\n";

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, body);

console.log(
  url && key
    ? "story config: wrote Supabase coordinates for " + url
    : "story config: no Supabase env set — the story shows the seed chapters"
);
