#!/usr/bin/env node
// The story site is plain static HTML (not part of the Next bundle), so it
// can't read process.env. This writes the public Supabase coordinates into
// public/story/config.js at build time; next build then copies it to out/.
// The file is gitignored — it is regenerated on every build.

import fs from "node:fs";
import path from "node:path";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || "";
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || "";

const target = path.join(process.cwd(), "public", "story", "config.js");
const body =
  "// Generated by tools/write-story-config.mjs — do not edit.\n" +
  "window.__TT_CONFIG = " +
  JSON.stringify({ url, key, basePath }) +
  ";\n";

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, body);

console.log(
  url && key
    ? "story config: wrote Supabase coordinates for " + url
    : "story config: no Supabase env set — story falls back to its built-in chapters"
);
