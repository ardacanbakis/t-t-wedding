-- ── Guest-facing RPCs ────────────────────────────────────────
-- SECURITY DEFINER: they bypass RLS, but only ever touch the single row
-- matching the caller's unguessable token.

-- (dropped first because the return type changed between versions —
-- CREATE OR REPLACE cannot alter a function's return type)
drop function if exists public.get_invitation(text);
create function public.get_invitation(p_token text)
returns table (
  name text,
  max_guests integer,
  status text,
  party_size integer,
  note text,
  personal_note text
)
language sql stable security definer
set search_path = public
as $$
  select i.name, i.max_guests, i.status, i.party_size, i.note, i.personal_note
  from public.invitations i
  where i.token = p_token;
$$;

create or replace function public.submit_rsvp(
  p_token text,
  p_answer text,
  p_party_size integer,
  p_note text
)
returns table (status text, party_size integer)
language plpgsql security definer
set search_path = public
as $$
declare
  v_deadline timestamptz;
  v_max integer;
  v_size integer;
begin
  if p_answer not in ('accepted', 'declined') then
    raise exception 'invalid';
  end if;

  begin
    select s.value::timestamptz into v_deadline
    from public.settings s where s.key = 'rsvpDeadline';
  exception when others then
    v_deadline := null;  -- unparsable deadline: fail open, admin will notice
  end;
  if v_deadline is not null and now() > v_deadline then
    raise exception 'locked';
  end if;

  select i.max_guests into v_max
  from public.invitations i where i.token = p_token;
  if not found then
    raise exception 'invalid';
  end if;

  v_size := greatest(1, coalesce(p_party_size, 1));
  if v_max is not null then
    v_size := least(v_size, v_max);
  end if;
  v_size := least(v_size, 99);
  if p_answer = 'declined' then
    v_size := 0;
  end if;

  return query
  update public.invitations i
  set status       = p_answer,
      party_size   = v_size,
      note         = nullif(left(coalesce(p_note, ''), 2000), ''),
      responded_at = now(),
      updated_at   = now()
  where i.token = p_token
  returning i.status, i.party_size;
end;
$$;

-- Lock the functions down to exactly the roles that need them.
create or replace function public.general_track(p_kind text)
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  if p_kind not in ('opens', 'yes') then
    return;
  end if;
  update public.general_stats set count = count + 1 where kind = p_kind;
end;
$$;

