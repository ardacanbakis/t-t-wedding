-- Admin check. SECURITY DEFINER so it can read admin_emails even though
-- that table has no policies of its own.
create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_emails
    where email = coalesce(auth.jwt() ->> 'email', '')
  );
$$;

-- Invitations: admins only. Guests never touch the table directly —
-- they go through the RPCs below, which look rows up by token.
drop policy if exists "admin full access" on public.invitations;
create policy "admin full access" on public.invitations
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Settings: anyone may read (date, venue, deadline are public to guests);
-- only admins may write.
drop policy if exists "settings are readable" on public.settings;
create policy "settings are readable" on public.settings
  for select to anon, authenticated
  using (true);

drop policy if exists "admin writes settings" on public.settings;
create policy "admin writes settings" on public.settings
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Story chapters: readable by everyone (the story site is public),
-- writable only by admins.
drop policy if exists "story is readable" on public.story_chapters;
create policy "story is readable" on public.story_chapters
  for select to anon, authenticated
  using (true);

drop policy if exists "admin writes story" on public.story_chapters;
create policy "admin writes story" on public.story_chapters
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- General stats: readable by everyone (the counts aren't secret), and only
-- ever changed through the SECURITY DEFINER RPC below.
drop policy if exists "general stats readable" on public.general_stats;
create policy "general stats readable" on public.general_stats
  for select to anon, authenticated
  using (true);

