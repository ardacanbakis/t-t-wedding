--   tables      [{ id, name, seats, x?, y? }]        x/y reserved for a floor plan
--   assignments { tableId: { invitationId: seats } } a party can span tables
--   heads       { invitationId: headcount }          overrides the derived count
create table if not exists public.seating_plans (
  id bigint generated by default as identity primary key,
  name text not null default 'Main plan',
  tables jsonb not null default '[]'::jsonb,
  assignments jsonb not null default '{}'::jsonb,
  heads jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- Optional individual attendee names for multi-person invitations, so the
-- printable venue list can name each person: people[invitationId] = ["A", "B"].
alter table public.seating_plans
  add column if not exists people jsonb not null default '{}'::jsonb;

alter table public.seating_plans enable row level security;

drop policy if exists "admin full access seating" on public.seating_plans;
create policy "admin full access seating" on public.seating_plans
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());


-- ── Guestbook (wishes) ───────────────────────────────────────
-- Notes guests leave for the couple. Admin-only table: guests write through
-- submit_wish() and read through get_wishes(), which returns only the notes
-- the couple has approved for the public wall (/wishes/).
create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  invitation_id bigint references public.invitations (id) on delete set null,
  name text not null,
  message text not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.wishes enable row level security;

drop policy if exists "admin full access wishes" on public.wishes;
create policy "admin full access wishes" on public.wishes
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- From a personal link (p_token) the note is tied to that invitation and the
-- name defaults to it; from the general pages (no token) a name is required.
-- The anon key is public, so the caps below keep a leaked link or a script
-- from flooding the book: 5 notes per invitation, 200 unreviewed anonymous
-- notes, 30 notes a minute overall.
create or replace function public.submit_wish(p_token text, p_name text, p_message text)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_inv_id bigint;
  v_inv_name text;
  v_name text := left(btrim(coalesce(p_name, '')), 80);
  v_msg text := left(btrim(coalesce(p_message, '')), 1000);
begin
  if v_msg = '' then
    raise exception 'empty';
  end if;
  if coalesce((select s.value from public.settings s where s.key = 'wishesOpen'), 'true') = 'false' then
    raise exception 'closed';
  end if;
  if (select count(*) from public.wishes w where w.created_at > now() - interval '1 minute') >= 30 then
    raise exception 'busy';
  end if;

  if coalesce(p_token, '') <> '' then
    select i.id, i.name into v_inv_id, v_inv_name from public.invitations i where i.token = p_token;
    if not found then
      raise exception 'invalid';
    end if;
    if (select count(*) from public.wishes w where w.invitation_id = v_inv_id) >= 5 then
      raise exception 'limit';
    end if;
    if v_name = '' then
      v_name := v_inv_name;
    end if;
  else
    if v_name = '' then
      raise exception 'name';
    end if;
    if (select count(*) from public.wishes w where w.invitation_id is null and not w.approved) >= 200 then
      raise exception 'limit';
    end if;
  end if;

  insert into public.wishes (invitation_id, name, message) values (v_inv_id, v_name, v_msg);
end;
$$;

create or replace function public.get_wishes()
returns table (name text, message text, created_at timestamptz)
language sql stable security definer
set search_path = public
as $$
  select w.name, w.message, w.created_at
  from public.wishes w
  where w.approved
  order by w.created_at;
$$;

revoke all on function public.submit_wish(text, text, text) from public;
revoke all on function public.get_wishes()                  from public;
grant execute on function public.submit_wish(text, text, text) to anon, authenticated;
grant execute on function public.get_wishes()                  to anon, authenticated;
