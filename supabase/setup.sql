-- Admin check. SECURITY DEFINER so it can read admin_emails even though
-- that table has no policies of its own.
create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_emails
    where email = coalesce(auth.jwt() ->> 'email', '')
  );
$$;

-- Invitations: admins only. Guests never touch the table directly —
-- they go through the RPCs below, which look rows up by token.
drop policy if exists "admin full access" on public.invitations;
create policy "admin full access" on public.invitations
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Settings: anyone may read (date, venue, deadline are public to guests);
